-- ── One open request per stay ───────────────────────────────────────────────
-- The same shape as D-007's one-CHECKED_IN-stay-per-room index, and for the same
-- reason: a guest double-tapping "Request 2pm checkout" on hotel wifi is the
-- most common duplicate in this product (#8), and two REQUESTED rows would mean
-- the desk deciding one and the other sitting there for ever.
--
-- A partial unique index rather than an idempotency key, because the constraint
-- is true regardless of how the second row arrives — a second device, a second
-- tab, or the desk. `requestCheckoutChange()` returns the existing row on
-- conflict rather than raising.

CREATE UNIQUE INDEX IF NOT EXISTS "checkout_requests_one_open_per_stay"
  ON "checkout_requests" ("stay_id")
  WHERE "status" = 'REQUESTED';
