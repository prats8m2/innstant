--
-- A tier is an HOUR, not a duration. "Checkout at 2pm" is what a guest picks and
-- what `stays.scheduled_checkout_at` becomes; "three extra hours" is derived
-- from the stay's own checkout time, so a guest already due out at 1pm reads
-- "one extra hour" for the same row.
--
-- An extra NIGHT is deliberately absent. Pricing one needs a nightly rate — a
-- rate plan for a room type on a date — which CLAUDE.md #11 forbids putting on a
-- room and #12 reserves the names for. Late checkout is a service fee; another
-- night is a booking (D-033).
